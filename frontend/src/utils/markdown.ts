import type { PaperAnalysisResponse } from "../types/paper";

/** 분석 결과를 가독성 높은 Markdown 문서 문자열로 변환합니다. */
export function buildPaperMarkdown(analysis: PaperAnalysisResponse): string {
  const authorsLine =
    analysis.authors.length > 0 ? analysis.authors.join(", ") : "정보 없음";

  const contributionsMd = analysis.key_contributions
    .map((item, idx) => `${idx + 1}. ${item}`)
    .join("\n");

  const glossaryMd = analysis.glossary
    .map((item) => `| **${item.term}** | ${item.definition} |`)
    .join("\n");

  const pdfSection = analysis.pdf_url ? `- **원문 PDF:** ${analysis.pdf_url}\n` : "";

  return `# ${analysis.title}

- **식별자 (arXiv ID):** \`${analysis.arxiv_id}\`
- **입문자 난이도:** ${analysis.difficulty_level}
- **저자:** ${authorsLine}
${analysis.published_at ? `- **발행일:** ${analysis.published_at}\n` : ""}${pdfSection}
---

## 1. 한 줄 핵심 요약

> ${analysis.one_line_summary}

## 2. 비전공자를 위한 쉬운 비유 설명

${analysis.easy_explanation}

## 3. 기존 대비 핵심 기여

${contributionsMd}

## 4. AI 용어 사전

| 용어 | 쉬운 뜻풀이 |
| --- | --- |
${glossaryMd}

---
*Generated by EasyPaper AI*
`;
}

/** 생성된 Markdown 텍스트를 브라우저 파일 다운로드로 내보냅니다. */
export function downloadPaperMarkdown(analysis: PaperAnalysisResponse): void {
  const markdown = buildPaperMarkdown(analysis);
  const blob = new Blob([markdown], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);

  const safeId = analysis.arxiv_id.replace(/[^a-zA-Z0-9._-]/g, "_");
  const link = document.createElement("a");
  link.href = url;
  link.download = `easypaper-${safeId}.md`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
